/// Radius tokens from the **Rota design system**.
///
/// Source: `Rota_Design_System.pdf` — seção *Raio*.
abstract final class AppRadii {
  /// `6px` — Chips e badges de status (ex.: "Rota recalculada").
  static const double radiusSm = 6;

  /// `12px` — Campos de texto, botões, cards de endereço.
  static const double radiusMd = 12;

  /// `24px` — Bottom sheet de rota, modais, botão Iniciar em destaque.
  static const double radiusLg = 24;
}